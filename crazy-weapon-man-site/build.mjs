// Builds the deployable game into public/ from game-src/.
//
//   node build.mjs          write public/
//   node build.mjs --check  exit 1 if public/ is out of date (used by CI)
//
// No dependencies. Cloudflare deploys public/ as-is, so the built output is committed.
//
// Load order (see game-src/manifest.json):
//   1. core/*.js     one closure, split into files at top-level statement boundaries.
//                    00-setup-world.js opens the closure, 99-boot.js closes it and starts the loop.
//   2. systems/*.js  run INSIDE that closure, just before 99-boot.js, so they can read and
//                    replace core functions (hurt, killE, draw, ...).
//   3. addons/*.js   separate <script> tags that run after the game starts. They can only see
//                    globals and the DOM, not closure variables.
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(ROOT, 'game-src');
const OUT = path.join(ROOT, 'public');
const check = process.argv.includes('--check');

const read = f => fs.readFileSync(path.join(SRC, f), 'utf8');
const manifest = JSON.parse(read('manifest.json'));
const hash = s => crypto.createHash('sha256').update(s).digest('hex').slice(0, 10);
const banner = f => `\n/* ---- ${f} ---- */\n`;

const game =
  '/* Crazy Weapon Man — generated by build.mjs from game-src/. Do not edit; edit game-src. */\n' +
  [...manifest.core, ...manifest.systems, manifest.boot].map(f => banner(f) + read(f).replace(/\s*$/, '\n')).join(';\n');
const css = read('shell/styles.css');

const files = new Map();
files.set('game.js', game);
files.set('styles.css', css);
const addonTags = manifest.addons.map(f => {
  const name = 'addons/' + path.basename(f);
  const src = read(f);
  files.set(name, src);
  return `<script src="/${name}?v=${hash(src)}"></script>`;
});
const html = read('shell/shell.html')
  .replace('<!--STYLES-->', `<link rel="stylesheet" href="/styles.css?v=${hash(css)}">`)
  .replace('<!--SCRIPTS-->', [`<script src="/game.js?v=${hash(game)}"></script>`, ...addonTags].join('\n'));
files.set('index.html', html);

// Everything in public/ that the build does not produce (other than assets/) is stale.
const listOut = (dir, base = '') =>
  fs.existsSync(dir)
    ? fs.readdirSync(dir, { withFileTypes: true }).flatMap(d =>
        d.isDirectory() ? listOut(path.join(dir, d.name), base + d.name + '/') : [base + d.name])
    : [];
const stale = listOut(OUT).filter(f => !files.has(f) && !f.startsWith('assets/'));
const changed = [...files].filter(([f, s]) => !fs.existsSync(path.join(OUT, f)) || fs.readFileSync(path.join(OUT, f), 'utf8') !== s).map(([f]) => f);

if (check) {
  if (changed.length || stale.length) {
    console.error('public/ is out of date. Run: node crazy-weapon-man-site/build.mjs');
    for (const f of changed) console.error('  changed: ' + f);
    for (const f of stale) console.error('  stale:   ' + f);
    process.exit(1);
  }
  console.log('public/ is up to date.');
} else {
  for (const f of stale) fs.rmSync(path.join(OUT, f));
  for (const [f, s] of files) {
    fs.mkdirSync(path.dirname(path.join(OUT, f)), { recursive: true });
    fs.writeFileSync(path.join(OUT, f), s);
  }
  for (const d of ['game', 'game-safe']) fs.rmSync(path.join(OUT, d), { recursive: true, force: true });
  console.log(`built ${files.size} files (${(game.length / 1024).toFixed(0)} KB game.js), removed ${stale.length} stale`);
}
